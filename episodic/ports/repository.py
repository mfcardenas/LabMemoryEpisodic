"""Contratos de persistencia del dominio episódico.

Los servicios de aplicación dependen de estos protocolos,
nunca de SQLite, Qdrant ni filesystem directamente.
"""
from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional, Protocol, Tuple

from episodic.domain.entities import (
    Annotation,
    CaptureSession,
    Entity,
    Episode,
    Evidence,
    Observation,
    Representation,
    Source,
)
from episodic.domain.captures import Capture, Job, JobState
from episodic.domain.times import Interval
from episodic.domain.types import EvidenceState, IndexingState, ValidationState
from episodic.domain.episodes import MicroEpisode
from episodic.domain.passages import Passage
from episodic.domain.processing import Event, ProcessingRun, ProcessingWindow
from episodic.domain.summaries import Summary
from episodic.domain.provenance import Asset, Environment, EvidenceReference
from episodic.domain.relations import Hypothesis, Relation
from episodic.domain.watch import ActivityEntry, ActivityLevel, InboxFile, InboxFileState


class EpisodicRepository(Protocol):
    """Fuente de verdad (SQLite): CRUD para todas las entidades."""

    # -- Sources --
    def save_environment(self, environment: Environment) -> None: ...
    def get_environment(self, environment_id: str) -> Optional[Environment]: ...
    def list_environments(self) -> List[Environment]: ...

    def save_source(self, source: Source) -> None: ...
    def get_source(self, source_id: str) -> Optional[Source]: ...
    def list_sources(self) -> List[Source]: ...

    # -- Sessions --
    def save_session(self, session: CaptureSession) -> None: ...
    def get_session(self, session_id: str) -> Optional[CaptureSession]: ...

    # -- Evidence --
    def save_evidence(self, evidence: Evidence) -> None: ...
    def get_evidence(self, evidence_id: str) -> Optional[Evidence]: ...
    def find_evidence_by_key(
        self, source_id: str, session_id: str, external_capture_id: str,
    ) -> Optional[Evidence]:
        """Buscar por clave de idempotencia."""
        ...
    def update_evidence_state(
        self, evidence_id: str, state: EvidenceState,
    ) -> None: ...
    def list_evidence_for_episode(self, episode_id: str) -> List[Evidence]: ...
    def list_episode_ids_for_evidence(self, evidence_id: str) -> List[str]: ...

    # -- Observations --
    def save_observation(self, obs: Observation) -> None: ...
    def list_observations_for_episode(
        self, episode_id: str,
    ) -> List[Observation]: ...
    def list_observations_for_entity(
        self, entity_id: str, limit: int = 100, cursor: Optional[str] = None,
    ) -> Tuple[List[Observation], Optional[str]]:
        """Paginación con cursor — no scroll(limit=10000)."""
        ...
    def list_observations_for_asset(self, asset_id: str) -> List[Observation]: ...
    def list_observations(
        self, environment_id: Optional[str] = None,
    ) -> List[Observation]: ...

    # -- Episodes --
    def save_episode(self, episode: Episode) -> None: ...
    def get_episode(self, episode_id: str) -> Optional[Episode]: ...
    def find_episode_by_external_id(
        self, external_id: str,
    ) -> Optional[Episode]: ...
    def list_episodes(
        self, source_id: Optional[str] = None,
        interval: Optional[Interval] = None,
        limit: int = 50, cursor: Optional[str] = None,
    ) -> Tuple[List[Episode], Optional[str]]: ...
    def set_episode_visibility(
        self, episode_id: str, visible: bool,
    ) -> None: ...
    def list_episodes_for_environment(self, environment_id: str) -> List[Episode]: ...
    def delete_episode_record(self, episode_id: str) -> bool: ...

    # -- Annotations --
    def save_annotation(self, ann: Annotation) -> None: ...
    def list_annotations_for_episode(
        self, episode_id: str,
    ) -> List[Annotation]: ...
    def get_latest_annotation(
        self, episode_id: str,
    ) -> Optional[Annotation]: ...

    # -- Entities --
    def save_entity(self, entity: Entity) -> None: ...
    def get_entity(self, entity_id: str) -> Optional[Entity]: ...
    def list_entities(self) -> List[Entity]: ...

    # -- Fase 2: activos, procesamiento, composición y relaciones --
    def save_asset(self, asset: Asset) -> None: ...
    def get_asset(self, asset_id: str) -> Optional[Asset]: ...
    def find_asset_by_hash(self, content_hash: str) -> Optional[Asset]: ...
    def list_assets(self, environment_id: Optional[str] = None) -> List[Asset]: ...
    def save_processing_run(self, run: ProcessingRun) -> None: ...
    def get_processing_run(self, run_id: str) -> Optional[ProcessingRun]: ...
    def save_processing_window(self, window: ProcessingWindow) -> None: ...
    def get_processing_window(self, window_id: str) -> Optional[ProcessingWindow]: ...
    def list_processing_windows_for_asset(self, asset_id: str) -> List[ProcessingWindow]: ...
    def save_evidence_reference(self, reference: EvidenceReference) -> None: ...
    def get_evidence_reference(self, reference_id: str) -> Optional[EvidenceReference]: ...
    def list_evidence_references_for_asset(
        self, asset_id: str,
    ) -> List[EvidenceReference]: ...
    def get_observation(self, observation_id: str) -> Optional[Observation]: ...
    def save_event(self, event: Event) -> None: ...
    def get_event(self, event_id: str) -> Optional[Event]: ...
    def get_events(self, event_ids: List[str]) -> Dict[str, Event]: ...
    def list_events(self, episode_id: str) -> List[Event]: ...
    def get_event_neighbors(
        self, event_id: str, before: int = 1, after: int = 1
    ) -> Tuple[List[Event], List[Event]]: ...
    def count_events(self) -> int: ...
    def link_events_to_episode(self, episode_id: str, observation_ids: List[str]) -> int: ...
    def delete_events_for_asset(self, asset_id: str, keep_ids: List[str]) -> List[str]: ...
    def save_microepisode(self, microepisode: MicroEpisode) -> None: ...
    def get_microepisode(self, microepisode_id: str) -> Optional[MicroEpisode]: ...
    def list_microepisodes(
        self, environment_id: Optional[str] = None,
    ) -> List[MicroEpisode]: ...
    def delete_microepisode(self, microepisode_id: str) -> bool: ...
    def save_relation(self, relation: Relation) -> None: ...
    def get_relation(self, relation_id: str) -> Optional[Relation]: ...
    def list_relations(
        self,
        relation_type: Optional[str] = None,
        node_type: Optional[str] = None,
        node_id: Optional[str] = None,
        validation_state: Optional[ValidationState] = None,
    ) -> List[Relation]: ...
    def save_hypothesis(self, hypothesis: Hypothesis) -> None: ...
    def get_hypothesis(self, hypothesis_id: str) -> Optional[Hypothesis]: ...
    def list_hypotheses(
        self, node_type: Optional[str] = None, node_id: Optional[str] = None,
    ) -> List[Hypothesis]: ...

    # -- Representations (outbox) --
    def save_representation(self, rep: Representation) -> None: ...
    def list_pending_representations(
        self, limit: int = 100,
    ) -> List[Representation]: ...
    def update_representation_state(
        self, rep_id: str, state: IndexingState,
        qdrant_point_id: Optional[str] = None,
    ) -> None: ...
    def list_representations_for_target(
        self, target_id: str,
    ) -> List[Representation]: ...
    def get_indexing_summary(self) -> Dict[str, int]:
        """Conteos de la outbox por estado, incluyendo ``total``."""
        ...

    # -- Captures & jobs --
    def save_capture(self, capture: Capture) -> None: ...
    def get_capture(self, capture_id: str) -> Optional[Capture]: ...
    def find_capture_for_episode(self, episode_id: str) -> Optional[Capture]: ...
    def list_captures(
        self, environment_id: Optional[str] = None, limit: int = 50,
    ) -> List[Capture]: ...
    def save_job(self, job: Job) -> None: ...
    def get_job(self, job_id: str) -> Optional[Job]: ...
    def list_jobs(
        self, states: Optional[List[JobState]] = None, target_id: Optional[str] = None,
    ) -> List[Job]: ...
    def list_recent_jobs(self, limit: int = 50) -> List[Job]: ...

    # -- Entrada automática y registro de ejecución --
    def save_inbox_file(self, item: InboxFile) -> None: ...
    def list_live_inbox_files(self, source_name: str) -> List[InboxFile]: ...
    def list_inbox_group_keys(self, source_name: str) -> List[str]: ...
    def list_inbox_files(
        self,
        source_name: Optional[str] = None,
        states: Optional[List[InboxFileState]] = None,
        limit: int = 200,
    ) -> List[InboxFile]: ...
    def count_inbox_files(self, source_name: str) -> Dict[str, int]: ...
    def append_activity(self, entry: ActivityEntry) -> int: ...
    def list_activity(
        self,
        after_id: int = 0,
        limit: int = 200,
        component: Optional[str] = None,
        levels: Optional[List[ActivityLevel]] = None,
    ) -> List[ActivityEntry]: ...
    def prune_activity(
        self, keep: int, levels: Optional[List[ActivityLevel]] = None
    ) -> int: ...
    # -- Pasajes (proyección de eventos y observaciones con contenido) --
    def replace_episode_passages(self, episode_id: str, passages: List[Passage]) -> List[str]: ...
    def delete_episode_passages(self, episode_id: str) -> List[str]: ...
    def get_passages(self, passage_ids: List[str]) -> Dict[str, Passage]: ...
    def list_passages_for_episode(self, episode_id: str) -> List[Passage]: ...
    def count_passages(self) -> int: ...
    def search_passages(
        self,
        match: str,
        limit: int,
        *,
        environment_ids: Tuple[str, ...] = (),
        source_ids: Tuple[str, ...] = (),
        modalities: Tuple[str, ...] = (),
        kinds: Tuple[str, ...] = (),
        start_ms: Optional[int] = None,
        end_ms: Optional[int] = None,
    ) -> List[Tuple[str, str, float, str]]: ...
    # -- Resúmenes jerárquicos (texto generado, con revisiones) --
    def save_summary(self, summary: Summary) -> None: ...
    def get_summary(self, summary_id: str) -> Optional[Summary]: ...
    def get_current_summary(self, scope: str, scope_key: str) -> Optional[Summary]: ...
    def list_summary_revisions(self, scope: str, scope_key: str) -> List[Summary]: ...
    def list_current_summaries(
        self, scope: str, prefix: Optional[str] = None, limit: int = 500
    ) -> List[Summary]: ...
    def count_summaries(self, scope: Optional[str] = None) -> int: ...
    def get_system_state(self, name: str) -> Optional[Any]: ...
    def set_system_state(self, name: str, value: Any) -> None: ...
    def acquire_lease(self, name: str, owner: str, ttl_seconds: float, now: float) -> bool: ...
    def get_lease(self, name: str) -> Optional[Tuple[str, float]]: ...
    def release_lease(self, name: str, owner: str) -> None: ...

    # -- Lifecycle --
    def begin_transaction(self) -> None: ...
    def commit_transaction(self) -> None: ...
    def rollback_transaction(self) -> None: ...


class EvidenceStore(Protocol):
    """Almacén de archivos de evidencia con hashing y referencias."""

    def store(self, data: bytes, filename: str) -> Tuple[str, str]:
        """Guardar blob atómicamente → (internal_uri, content_hash)."""
        ...

    def store_file(self, source_path: str | Path) -> Tuple[str, str, int]:
        """Copiar un archivo al almacén gestionado y devolver URI, hash y tamaño."""
        ...

    def retrieve(self, internal_uri: str) -> bytes:
        """Leer blob por URI interna."""
        ...

    def resolve_path(self, internal_uri: str) -> Path:
        """Resolver una URI interna sin permitir escapar del almacén."""
        ...

    def exists(self, internal_uri: str) -> bool: ...

    def delete_if_unreferenced(
        self, internal_uri: str, content_hash: str,
    ) -> bool:
        """Eliminar blob solo si no tiene referencias vigentes."""
        ...
